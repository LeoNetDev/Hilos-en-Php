import threading
import queue
import time
import random

cola = queue.Queue()

for numero in range(1, 25):
    cola.put((numero, random.randint(1, 5)))

integrantes = ["Mateo", "Lucas", "Juan", "Valentin"]

resultados = {
    nombre: {"ids": [], "tamano": 0}
    for nombre in integrantes
}

lock = threading.Lock()


def procesar(nombre):
    for i in range(6):
        documento, tamano = cola.get()

        print(nombre, "procesa documento", documento)

        time.sleep(random.uniform(0.2, 0.6))

        with lock:
            resultados[nombre]["ids"].append(documento)
            resultados[nombre]["tamano"] += tamano

        print(nombre, "termino documento", documento)

        cola.task_done()


inicio = time.perf_counter()

hilos = []

for nombre in integrantes:
    hilo = threading.Thread(target=procesar, args=(nombre,))
    hilos.append(hilo)
    hilo.start()

for hilo in hilos:
    hilo.join()

fin = time.perf_counter()

print("\nRESUMEN FINAL")

todos = []

for nombre in integrantes:
    datos = resultados[nombre]
    ids = sorted(datos["ids"])
    todos.extend(ids)

    print("\nTrabajador:", nombre)
    print("Documentos:", len(ids))
    print("IDs:", ids)
    print("Tamano acumulado:", datos["tamano"], "MB")

print("\nCOMPROBACIONES")

print("Total procesado:", len(todos))
print("Documentos pendientes:", cola.qsize())
print("IDs sin repetir:", len(todos) == len(set(todos)))
print("IDs del 1 al 24:", sorted(todos) == list(range(1, 25)))
print("Seis por trabajador:", all(len(resultados[n]["ids"]) == 6 for n in integrantes))
print("Cuatro hilos finalizados:", all(not h.is_alive() for h in hilos))
print("Tiempo total:", round(fin - inicio, 3), "segundos")